package videoaulas.ComparadoreOP;

public class Comparadores {

    public static void main(String[] args) {

        boolean resultado = 10!=11;     //diferença
        boolean resultado2 = 10==20;    //igualdade
        boolean resultado3 = 10>7;      // maior ou menor à
        boolean resultado4 = 10>=11;     // maior ou igual à

        System.out.println(resultado);
        System.out.println(resultado2);
        System.out.println(resultado3);
        System.out.println(resultado4);
    }
}
